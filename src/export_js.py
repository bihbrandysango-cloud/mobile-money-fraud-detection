"""Turn the robust model into one JavaScript file that runs in any web browser.

No server is needed: the page loads fraud-alarm.js and calls
    FraudAlarm.check({kind, amount, balance, hour, receiverIsNew, sameAmountMoved})
which returns the same answer as scoring.check() in Python.

Reasons use exact TreeSHAP (Lundberg et al. 2018, Algorithm 2), the same
method as the Python version, so verdicts and reasons should match.
tests/parity.py checks this against Python on thousands of cases.

Usage: python src/export_js.py
Output: deploy/web/fraud-alarm.js
"""
import json
import pathlib

import lightgbm as lgb

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
OUT = ROOT / "deploy" / "web" / "fraud-alarm.js"


def flatten(tree):
    """Tree -> parallel arrays. Children >= 0 are node indexes, < 0 are ~leaf indexes."""
    feat, thr, left, right, value, cover, leaves, leaf_cover = [], [], [], [], [], [], [], []

    def visit(n):
        if "leaf_index" in n or "split_index" not in n:
            leaves.append(n["leaf_value"]); leaf_cover.append(n.get("leaf_count", 0))
            return ~(len(leaves) - 1)
        i = len(feat)
        feat.append(n["split_feature"]); thr.append(n["threshold"])
        left.append(None); right.append(None); value.append(n["internal_value"]); cover.append(n["internal_count"])
        left[i] = visit(n["left_child"])
        right[i] = visit(n["right_child"])
        return i

    root = visit(tree["tree_structure"])
    return {"f": feat, "t": thr, "l": left, "r": right, "v": value, "c": cover,
            "leaf": leaves, "lc": leaf_cover, "root": root}


def build():
    """Return the JavaScript text for the current model."""
    booster = lgb.Booster(model_file=str(REPORTS / "model_robust.txt"))
    dump = booster.dump_model()
    assert dump["objective"].startswith("binary sigmoid:1")
    model = {
        "features": dump["feature_names"],
        "trees": [flatten(t) for t in dump["tree_info"]],
        "threshold": json.loads((REPORTS / "alert_threshold.json").read_text())["threshold"],
        "typicalReceiver": json.loads((REPORTS / "receiver_profiles.json").read_text())["established_receiver"],
    }
    js = (ENGINE.replace("__MODEL__", json.dumps(model, separators=(",", ":"))))
    return js


def main():
    js = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(js.encode("utf-8"))
    print(f"{OUT} ({OUT.stat().st_size / 1024:.0f} KB)")


ENGINE = r"""/*! Mobile money fraud alarm (demo). Trained on PaySim, simulated data,
    not real MTN or Orange customers. Generated by src/export_js.py. */
(function (root) {
  "use strict";
  var M = __MODEL__;
  var F = M.features;
  var idx = {};
  F.forEach(function (name, i) { idx[name] = i; });

  // Same inputs as scoring.build_features in Python.
  function buildFeatures(kind, amount, balance, hour, receiver, sameAmountMoved) {
    var x = new Array(F.length);
    x[idx.is_transfer] = kind === "send" ? 1 : 0;
    x[idx.amount] = amount;
    x[idx.log_amount] = Math.log1p(amount);
    x[idx.orig_bal_before] = balance;
    x[idx.amount_to_balance] = balance > 0 ? amount / balance : -1;
    x[idx.empties_account] = balance > 0 && amount >= balance ? 1 : 0;
    x[idx.hour_of_day] = hour;
    x[idx.dest_bal_before] = receiver.dest_bal_before;
    x[idx.dest_prior_in_count] = receiver.dest_prior_in_count;
    x[idx.dest_prior_in_amount] = receiver.dest_prior_in_amount;
    x[idx.dest_prior_out_count] = receiver.dest_prior_out_count;
    x[idx.dest_hours_since_last] = receiver.dest_hours_since_last;
    x[idx.pair_match] = sameAmountMoved ? 1 : 0;
    return x;
  }

  // Raw score: walk each tree to its leaf.
  function rawScore(x) {
    var raw = 0;
    M.trees.forEach(function (t) {
      var node = t.root;
      while (node >= 0) node = x[t.f[node]] <= t.t[node] ? t.l[node] : t.r[node];
      raw += t.leaf[~node];
    });
    return raw;
  }

  // Exact TreeSHAP (Lundberg, Erion & Lee 2018, Algorithm 2), path-dependent,
  // using training counts as cover, as LightGBM's pred_contrib and shap do.
  function treeShap(t, x, phi) {
    function value(n) { return n < 0 ? t.leaf[~n] : t.v[n]; }
    function cover(n) { return n < 0 ? t.lc[~n] : t.c[n]; }
    function extend(m, pz, po, pi) {
      var l = m.length;
      m.push({ d: pi, z: pz, o: po, w: l === 0 ? 1 : 0 });
      for (var i = l - 1; i >= 0; i--) {
        m[i + 1].w += po * m[i].w * (i + 1) / (l + 1);
        m[i].w = pz * m[i].w * (l - i) / (l + 1);
      }
    }
    function unwind(m, i) {
      var l = m.length - 1, n = m[l].w, o = m[i].o, z = m[i].z;
      for (var j = l - 1; j >= 0; j--) {
        if (o !== 0) {
          var tmp = m[j].w;
          m[j].w = n * (l + 1) / ((j + 1) * o);
          n = tmp - m[j].w * z * (l - j) / (l + 1);
        } else {
          m[j].w = m[j].w * (l + 1) / (z * (l - j));
        }
      }
      for (var k = i; k < l; k++) { m[k].d = m[k + 1].d; m[k].z = m[k + 1].z; m[k].o = m[k + 1].o; }
      m.pop();
    }
    function unwoundSum(m, i) {
      var l = m.length - 1, total = 0, n = m[l].w, o = m[i].o, z = m[i].z;
      for (var j = l - 1; j >= 0; j--) {
        if (o !== 0) {
          var tmp = n * (l + 1) / ((j + 1) * o);
          total += tmp;
          n = m[j].w - tmp * z * (l - j) / (l + 1);
        } else {
          total += m[j].w * (l + 1) / (z * (l - j));
        }
      }
      return total;
    }
    function recurse(node, path, pz, po, pi) {
      var m = path.map(function (e) { return { d: e.d, z: e.z, o: e.o, w: e.w }; });
      extend(m, pz, po, pi);
      if (node < 0) {
        for (var i = 1; i < m.length; i++) phi[m[i].d] += unwoundSum(m, i) * (m[i].o - m[i].z) * value(node);
        return;
      }
      var f = t.f[node];
      var hot = x[f] <= t.t[node] ? t.l[node] : t.r[node];
      var cold = hot === t.l[node] ? t.r[node] : t.l[node];
      var iz = 1, io = 1;
      for (var k = 1; k < m.length; k++) {
        if (m[k].d === f) { iz = m[k].z; io = m[k].o; unwind(m, k); break; }
      }
      var c = cover(node);
      recurse(hot, m, iz * cover(hot) / c, io, f);
      recurse(cold, m, iz * cover(cold) / c, 0, f);
    }
    if (t.root < 0) return;
    recurse(t.root, [], 1, 1, -1);
  }

  function predict(x) {
    var raw = rawScore(x), contrib = new Array(F.length).fill(0);
    M.trees.forEach(function (t) { treeShap(t, x, contrib); });
    return { risk: 1 / (1 + Math.exp(-raw)), raw: raw, contrib: contrib };
  }

  function money(v) { return Math.round(v).toLocaleString("en-US"); }
  function pad(h) { return (h < 10 ? "0" : "") + h; }

  // Same sentences as scoring._plain in Python.
  function plain(key, x, kind) {
    var share = x[idx.amount_to_balance], hour = x[idx.hour_of_day];
    if (key === "amount_to_balance") {
      if (share < 0) return "The account showed no money before this";
      if (share > 1.001) return "The amount is more than the account showed";
      if (share >= 0.999) return "It takes all the money in the account";
      return "It takes " + Math.round(share * 100) + "% of the money in the account";
    }
    if (key === "pair_match") return x[idx.pair_match]
      ? "The same amount was just moved out the other way, a common thief pattern"
      : "No matching amount was just moved the other way";
    if (key === "dest_bal_before") {
      var isNew = x[idx.dest_prior_in_count] === 0;
      if (kind === "withdraw") return isNew ? "The agent account was empty and has no history"
                                            : "The agent account has a normal history";
      return isNew ? "The money goes to a new, empty account" : "The money goes to an account with a normal history";
    }
    if (key === "hour_of_day") {
      if (hour < 6) return "It happens at " + pad(hour) + ":00, in the middle of the night";
      return hour >= 7 && hour <= 20 ? "It happens at " + pad(hour) + ":00, during normal hours"
                                     : "It happens late, at " + pad(hour) + ":00";
    }
    if (key === "is_transfer") return kind === "send" ? "It sends money to another account"
                                                       : "It is a cash withdrawal at an agent";
    if (key === "amount") return "The amount is " + money(x[idx.amount]) + " FCFA";
    if (key === "orig_bal_before") return "The account had " + money(x[idx.orig_bal_before]) + " FCFA before";
    return key;
  }

  var GROUPS = {
    amount_to_balance: ["amount_to_balance", "empties_account"], amount: ["amount", "log_amount"],
    dest_bal_before: ["dest_bal_before", "dest_prior_in_count", "dest_prior_in_amount",
                      "dest_prior_out_count", "dest_hours_since_last"]
  };
  function groupOf(f) {
    for (var g in GROUPS) if (GROUPS[g].indexOf(f) >= 0) return g;
    return f;
  }

  /**
   * q = {kind: "send"|"withdraw", amount: FCFA > 0, balance: FCFA >= 0, hour: 0-23,
   *      receiverIsNew: bool, sameAmountMoved: bool}
   * returns {verdict: "stop"|"allow", headline, confidence, reasons: [3 sentences], risk}
   */
  function check(q) {
    if (q.kind !== "send" && q.kind !== "withdraw") throw new Error("kind must be 'send' or 'withdraw'");
    var amount = Number(q.amount), balance = Number(q.balance), hour = Math.round(Number(q.hour));
    if (!(amount > 0)) throw new Error("amount must be more than 0");
    if (!(balance >= 0)) throw new Error("balance must be 0 or more");
    if (!(hour >= 0 && hour <= 23)) throw new Error("hour must be 0-23");
    var t = M.typicalReceiver;
    var receiver = q.receiverIsNew
      ? { dest_bal_before: 0, dest_prior_in_count: 0, dest_prior_in_amount: 0, dest_prior_out_count: 0,
          dest_hours_since_last: -1 }
      : t;
    var x = buildFeatures(q.kind, amount, balance, hour, receiver, !!q.sameAmountMoved);
    var p = predict(x);
    var alert = p.risk >= M.threshold;

    var merged = {};
    F.forEach(function (f, i) { var g = groupOf(f); merged[g] = (merged[g] || 0) + p.contrib[i]; });
    var keys = Object.keys(merged).filter(function (k) { return alert ? merged[k] > 0 : merged[k] < 0; });
    keys.sort(function (a, b) { return Math.abs(merged[b]) - Math.abs(merged[a]); });

    return {
      verdict: alert ? "stop" : "allow",
      headline: alert ? "Check with the customer before the money moves" : "Looks normal, let it through",
      confidence: p.risk >= 0.5 || p.risk < M.threshold / 10 ? "very sure" : "fairly sure",
      reasons: keys.slice(0, 3).map(function (k) { return plain(k, x, q.kind); })
        .concat(alert ? ["About 4 in 10 alerts like this turn out to be honest customers, so check before acting"] : []),
      risk: p.risk
    };
  }

  var api = { check: check, _buildFeatures: buildFeatures, _predict: predict, _threshold: M.threshold,
              _typicalReceiver: M.typicalReceiver, _features: F };
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.FraudAlarm = api;
})(typeof self !== "undefined" ? self : this);
"""

if __name__ == "__main__":
    main()
